// @ts-check
import { defineConfig } from 'astro/config';
import mdx from '@astrojs/mdx';
import sitemap from '@astrojs/sitemap';
import tailwindcss from '@tailwindcss/vite';
import { unified } from '@astrojs/markdown-remark';
import redirectData from './src/data/redirects.json' with { type: 'json' };
import redirectsEn from './src/data/redirects-en.json' with { type: 'json' };
import { rehypeOdra } from './src/lib/rehype-odra.mjs';
import { rehypeMatchTables } from './src/lib/rehype-match-tables.mjs';
import { remarkPgn } from './src/lib/pgn/remark-pgn.mjs';
import { remarkFeaturedDedupe } from './src/lib/remark-featured-dedupe.mjs';
import { remarkArticleBadges } from './src/lib/remark-article-badges.mjs';
import { articleFiles } from './src/integrations/article-files.mjs';

/**
 * Deployment target
 * ------------------
 * SITE_URL  – origin of the deployed site, e.g. https://username.github.io or https://www.sk-odra.hr
 * BASE_PATH – sub-path the site lives under, e.g. /sk-odra/ for a GitHub Pages project site, or / for a custom domain
 *
 * The GitHub Actions workflow fills both automatically from actions/configure-pages,
 * so nothing has to be hardcoded when switching from username.github.io/repo to a custom domain.
 */
const site = process.env.SITE_URL || 'http://localhost:4321';
const rawBase = process.env.BASE_PATH || '/';
const base = rawBase.endsWith('/') ? rawBase : `${rawBase}/`;

/**
 * Old WordPress URL → new URL map (generated by scripts/migrate-wordpress.ts),
 * plus the former English pages (/en/…) → their Croatian equivalents.
 */
const redirects = Object.fromEntries(
  Object.entries({ ...(redirectData.paths ?? {}), ...(redirectsEn.paths ?? {}) })
    .filter(([from, to]) => from !== to && from !== '/')
    // Astro serves the redirect page under the base path, but does not prefix the destination
    .map(([from, to]) => [from, `${base.replace(/\/$/, '')}${to}`]),
);

export default defineConfig({
  site,
  base,
  trailingSlash: 'ignore',
  output: 'static',
  build: { format: 'directory' },

  redirects,

  markdown: {
    processor: unified({
      // chess games: ```pgn blocks and links to .pgn files become interactive viewers
      // the featured photo is not repeated inside the article text
      remarkPlugins: [remarkFeaturedDedupe, remarkArticleBadges, [remarkPgn, { base }]],
      rehypePlugins: [rehypeMatchTables, [rehypeOdra, { base }]],
    }),
  },

  image: {
    responsiveStyles: true,
  },

  integrations: [
    mdx(),
    // full-size photos and documents linked (not embedded) from articles
    articleFiles(),
    sitemap({
      filter: (page) => !page.includes('/admin/') && !page.includes('/404'),
    }),
  ],

  vite: {
    plugins: [tailwindcss()],
  },
});
